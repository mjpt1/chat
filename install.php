    echo '<p><a class="btn btn-primary" href="index.php">ورود به برنامه</a></p></div></main></body></html>';
    exit;
}

$preflight = neda_install_checks();
$pdoDrivers = class_exists('PDO') ? PDO::getAvailableDrivers() : [];
$hasMysql = in_array('mysql', $pdoDrivers, true);
$hasSqlite = in_array('sqlite', $pdoDrivers, true);

if (($_SERVER['REQUEST_METHOD'] ?? '') === 'POST') {
    $errors = array_merge($errors, $preflight);
    $driver = (($_POST['driver'] ?? 'mysql') === 'sqlite') ? 'sqlite' : 'mysql';
    if ($driver === 'mysql' && !$hasMysql) {
        $errors[] = 'PDO MySQL روی این هاست فعال نیست. از پشتیبانی بخواهید pdo_mysql را روشن کنند.';
    }
    if ($driver === 'sqlite' && !$hasSqlite) {
        $errors[] = 'PDO SQLite روی این هاست فعال نیست. برای سی‌پنل از MySQL استفاده کنید.';
    }
    if (!$errors) {
        try {
            if ($driver === 'sqlite') {
                $dir = __DIR__ . '/data';
                if (!is_dir($dir) && !mkdir($dir, 0755, true) && !is_dir($dir)) {
                    throw new RuntimeException('پوشه data ساخته نشد.');
                }
                $dbPath = $dir . '/mahsa.sqlite';
                $pdo = new PDO('sqlite:' . $dbPath);
                $pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
                $pdo->exec('PRAGMA foreign_keys = ON');
                neda_install_schema($pdo, __DIR__ . '/sql/schema.sqlite.sql');
                $cfg = ['driver' => 'sqlite', 'db_path' => $dbPath];
            } else {
                $cfg = [
                    'driver' => 'mysql',
                    'db_host' => trim((string) ($_POST['db_host'] ?? 'localhost')),
                    'db_port' => trim((string) ($_POST['db_port'] ?? '3306')),
                    'db_name' => trim((string) ($_POST['db_name'] ?? '')),
                    'db_user' => trim((string) ($_POST['db_user'] ?? '')),
                    'db_pass' => (string) ($_POST['db_pass'] ?? ''),
                ];
                if ($cfg['db_name'] === '' || $cfg['db_user'] === '') {
                    throw new RuntimeException('نام پایگاه داده و نام کاربری الزامی است.');
                }
                $dsn = sprintf(
                    'mysql:host=%s;port=%s;dbname=%s;charset=utf8mb4',
                    $cfg['db_host'],
                    $cfg['db_port'] ?: '3306',
                    $cfg['db_name']
                );
                $pdo = new PDO($dsn, $cfg['db_user'], $cfg['db_pass'], [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                ]);
                neda_install_schema($pdo, __DIR__ . '/sql/schema.sql');
            }
            $ok = true;
            $written = neda_install_write_config($configPath, $cfg);
            if (!$written) {
                $manual = "<?php\nreturn " . var_export($cfg, true) . ";\n";
            } elseif (!empty($_POST['remove_installer'])) {
                $deletedInstaller = @unlink(__FILE__);
            }
        } catch (Throwable $e) {
            $errors[] = 'اتصال یا ساخت جدول‌ها ناموفق بود. جزئیات: ' . $e->getMessage();
        }
    }
}

