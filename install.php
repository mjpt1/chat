$deletedInstaller = false;
$manual = '';

function neda_install_write_config(string $path, array $cfg): bool
{
    $export = var_export($cfg, true);
    $php = "<?php\n// generated by install.php — do not commit secrets\nreturn {$export};\n";
    return file_put_contents($path, $php) !== false;
}

function neda_install_schema(PDO $pdo, string $file): void
{
    $sql = file_get_contents($file);
    if ($sql === false) {
        throw new RuntimeException('فایل جدول‌ها خوانده نشد.');
    }
    foreach (array_filter(array_map('trim', explode(';', $sql))) as $chunk) {
        if ($chunk !== '') {
            $pdo->exec($chunk);
        }
    }
}

function neda_install_checks(): array
{
    $issues = [];
    if (version_compare(PHP_VERSION, '7.4.0', '<')) {
        $issues[] = 'نسخهٔ PHP باید ۷٫۴ یا بالاتر باشد. نسخهٔ فعلی: ' . PHP_VERSION;
    }
    if (!class_exists('PDO')) {
        $issues[] = 'افزونهٔ PDO روی سرور فعال نیست.';
    }
    if (!is_writable(__DIR__)) {
        $issues[] = 'پوشهٔ برنامه قابل نوشتن نیست. دسترسی نوشتن public_html را در سی‌پنل بررسی کنید.';
    }
    return $issues;
}

if (is_file($configPath) && empty($_GET['reinstall'])) {
    header('Content-Type: text/html; charset=utf-8');
